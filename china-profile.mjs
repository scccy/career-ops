function main() {
  const args = parseArgs();
  if (args.help || !args.input) {
    console.log('Usage: node china-profile.mjs --input resume.md [--profile-out config/profile.yml] [--profile-md-out modes/_profile.md] [--force]');
    return;
  }
  if (!existsSync(args.input)) throw new Error(`input not found: ${args.input}`);
  const text = readFileSync(args.input, 'utf-8');
  const info = extract(text);
  const profileOut = args['profile-out'] || 'config/profile.yml';
  const profileMdOut = args['profile-md-out'] || 'modes/_profile.md';
  const targets = [profileOut, profileMdOut];
  if (!args['dry-run'] && !args.force) {
    const existing = targets.filter((path) => existsSync(path));
    if (existing.length) {
      throw new Error(`refusing to overwrite existing user file(s): ${existing.join(', ')}. Add --force after you have backed up or reviewed them.`);
    }
  }
  if (!args['dry-run']) {
    for (const path of targets) mkdirSync(dirname(path), { recursive: true });
    writeFileSync(profileOut, buildProfile(info), 'utf-8');
    writeFileSync(profileMdOut, buildProfileMarkdown(info), 'utf-8');
  }
  console.log(JSON.stringify({
    extracted: info,
    missing: ['目标岗位', '期望薪资', '最低接受薪资', '当前求职状态', '到岗时间', 'BOSS 打招呼风格偏好'],
    wrote: args['dry-run'] ? [] : [profileOut, profileMdOut],
  }, null, 2));
}

main();
