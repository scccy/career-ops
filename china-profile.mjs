#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname } from 'path';
import { parseArgs } from './boss-common.mjs';

function lines(text) {
  return String(text || '').split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
}

function pickSection(text, names) {
  const all = lines(text);
  const start = all.findIndex((line) => names.some((name) => line.includes(name)));
  if (start === -1) return [];
  const out = [];
  for (let i = start + 1; i < all.length; i++) {
    if (/^#{1,6}\s+/.test(all[i]) || /^(教育|工作|项目|技能|证书|求职|自我评价)/.test(all[i])) break;
    out.push(all[i].replace(/^[-*]\s*/, ''));
  }
  return out.slice(0, 8);
}

function extract(text) {
  const phone = text.match(/1[3-9]\d{9}/)?.[0] || '待补充';
  const email = text.match(/[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/i)?.[0] || '待补充';
  const name = lines(text).find((line) => /^[\u4e00-\u9fa5]{2,4}$/.test(line)) || '待补充';
  const skills = pickSection(text, ['技能', '技能栈', '专业技能']).slice(0, 8);
  const projects = pickSection(text, ['项目', '项目经历']).slice(0, 5);
  const experience = pickSection(text, ['工作经历', '工作经验', '经历']).slice(0, 5);
  const certificates = pickSection(text, ['证书', '资格']).slice(0, 5);
  const city = text.match(/(北京|上海|广州|深圳|杭州|南京|成都|武汉|西安|苏州|天津|重庆|长沙|郑州|青岛|厦门|合肥)/)?.[0] || '待补充';
  const years = text.match(/(\d+)\s*年(?:工作)?经验/)?.[0] || '待补充';
  return { name, phone, email, city, skills, projects, experience, certificates, years };
}

function yamlList(items, indent = '    ') {
  if (!items.length) return `${indent}- "待补充"`;
  return items.map((item) => `${indent}- "${String(item).replace(/"/g, '\\"')}"`).join('\n');
}

