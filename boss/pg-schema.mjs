// boss/pg-schema.mjs — BOSS PostgreSQL 表结构（幂等建表）
//
// 2026-10 迁移：MySQL 的 boss_jobs / boss_config 迁到 PG；同时把原先的文件存储
// （发送日志 / 待发队列 / last-scan）也迁入 PG，使 BOSS 流程全部以 PG 为准。
import { query, ensureDatabaseExists } from './pg-db.mjs';

const DDL = [
  `CREATE TABLE IF NOT EXISTS boss_jobs (
     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     key_hash CHAR(64) NOT NULL UNIQUE,
     company VARCHAR(191) DEFAULT '',
     title VARCHAR(255) DEFAULT '',
     salary VARCHAR(128) DEFAULT '',
     city VARCHAR(128) DEFAULT '',
     hr_active VARCHAR(64) DEFAULT '',
     url VARCHAR(768) DEFAULT '',
     greeted SMALLINT DEFAULT 0,
     contact_state VARCHAR(32) NOT NULL DEFAULT 'never_contacted',
     salary_min NUMERIC(6,2) NULL,
     salary_max NUMERIC(6,2) NULL,
     score NUMERIC(4,2) NULL,
     llm_score NUMERIC(4,2) NULL,
     status VARCHAR(32) DEFAULT '',
     availability VARCHAR(16) NOT NULL DEFAULT 'unknown',
     manual_excluded SMALLINT NOT NULL DEFAULT 0,
     manual_exclusion_reason VARCHAR(255) DEFAULT '',
     scanned_at TIMESTAMPTZ NULL,
     raw JSONB NOT NULL,
     created_at TIMESTAMPTZ DEFAULT now(),
     updated_at TIMESTAMPTZ DEFAULT now()
   )`,
  `CREATE INDEX IF NOT EXISTS idx_boss_jobs_city_score ON boss_jobs (city, score)`,
  `CREATE INDEX IF NOT EXISTS idx_boss_jobs_company ON boss_jobs (company)`,
  `CREATE INDEX IF NOT EXISTS idx_boss_jobs_greeted ON boss_jobs (greeted)`,
  `CREATE INDEX IF NOT EXISTS idx_boss_jobs_salary ON boss_jobs (salary_min, salary_max)`,
  `CREATE INDEX IF NOT EXISTS idx_boss_jobs_scanned ON boss_jobs (scanned_at)`,
  `CREATE INDEX IF NOT EXISTS idx_boss_jobs_hr_active ON boss_jobs (hr_active)`,
  // 2026-10-30：LLM 深度解析（cv.md + JD → 标准 JSON）的匹配分单独一列，便于排序/筛选；
  // 整份解析结果存 raw.llm。存量库走 ADD COLUMN IF NOT EXISTS（幂等，ensureSchema 每次启动都会执行）。
  `ALTER TABLE boss_jobs ADD COLUMN IF NOT EXISTS llm_score NUMERIC(4,2) NULL`,
  `CREATE INDEX IF NOT EXISTS idx_boss_jobs_llm_score ON boss_jobs (llm_score)`,
  // llm_score 是**派生列**（真来源是 raw.llm.match.score）：整池重写（TRUNCATE + INSERT）一旦漏了这一列就会清空。
  // 这里每次启动做一次幂等回填——只有 NULL 且有 raw.llm 的行才动，没事时是空更新，代价可忽略。
  `UPDATE boss_jobs SET llm_score = (raw->'llm'->'match'->>'score')::numeric
     WHERE llm_score IS NULL AND jsonb_exists(raw, 'llm')`,

  `CREATE TABLE IF NOT EXISTS boss_config (
     name VARCHAR(128) NOT NULL PRIMARY KEY,
     value TEXT NOT NULL,
     updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
   )`,

  `CREATE TABLE IF NOT EXISTS boss_sent_log (
     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     sent_date DATE NOT NULL,
     sent_time TIME NULL,
     company TEXT DEFAULT '',
     title TEXT DEFAULT '',
     url TEXT DEFAULT '',
     status TEXT DEFAULT '',
     message TEXT DEFAULT '',
     error TEXT DEFAULT '',
     city TEXT DEFAULT '',
     created_at TIMESTAMPTZ DEFAULT now()
   )`,
  `CREATE INDEX IF NOT EXISTS idx_boss_sent_log_date ON boss_sent_log (sent_date)`,
  `CREATE INDEX IF NOT EXISTS idx_boss_sent_log_date_city ON boss_sent_log (sent_date, city)`,
  // 发送流水要能按 key_hash 直接回溯到岗位（原先只能靠 url/公司名，跨表核对很别扭）。存量库幂等补列。
  `ALTER TABLE boss_sent_log ADD COLUMN IF NOT EXISTS key_hash CHAR(64)`,
  `CREATE INDEX IF NOT EXISTS idx_boss_sent_log_key_hash ON boss_sent_log (key_hash)`,

  `CREATE TABLE IF NOT EXISTS boss_queue (
     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     queue_name TEXT NOT NULL,
     key_hash CHAR(64) NULL,
     payload JSONB NOT NULL,
     created_at TIMESTAMPTZ DEFAULT now()
   )`,
  `CREATE INDEX IF NOT EXISTS idx_boss_queue_name ON boss_queue (queue_name)`,

  `CREATE TABLE IF NOT EXISTS boss_runtime_state (
     state_key TEXT NOT NULL PRIMARY KEY,
     value TEXT NOT NULL,
     updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
   )`,
];

let _ready = null;

export function ensureSchema() {
  if (!_ready) {
    _ready = (async () => {
      await ensureDatabaseExists();
      for (const stmt of DDL) {
        await query(stmt);
      }
    })().catch((err) => { _ready = null; throw err; });
  }
  return _ready;
}
